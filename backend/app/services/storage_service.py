"""Private object storage service for NoteMint files.

All operations target the configured private Neon bucket. Object keys are
generated by the backend (never taken from client paths) and no public URLs
are ever constructed for stored documents.
"""

from __future__ import annotations

import logging
import re
import uuid
from pathlib import PurePosixPath
from typing import BinaryIO

from botocore.client import BaseClient
from botocore.exceptions import ClientError, EndpointConnectionError

from app.integrations.neon_storage import (
    StorageNotConfiguredError,
    StorageObjectNotFoundError,
    StorageUnavailableError,
    get_s3_client,
    get_storage_bucket,
)

logger = logging.getLogger(__name__)

# Clerk user ids look like "user_2abcDEF..." — restrictive on purpose so a
# crafted id can never inject path segments ("../", "/", ...).
_CLERK_USER_ID_PATTERN = re.compile(r"^user_[A-Za-z0-9]+$")
_SAFE_FILENAME_PATTERN = re.compile(r"^[A-Za-z0-9._-]+$")


class ObjectKeyError(ValueError):
    """Raised when a component of an object key is invalid or unsafe."""


def build_document_key(
    clerk_user_id: str,
    document_id: uuid.UUID | str,
    *,
    filename: str = "original.pdf",
) -> str:
    """Build the canonical object key for a document's original file.

    Format: ``users/{clerk_user_id}/documents/{document_uuid}/original.pdf``

    Raises:
        ObjectKeyError: if any component is missing or would be unsafe.
    """
    if not _CLERK_USER_ID_PATTERN.match(clerk_user_id):
        raise ObjectKeyError("invalid clerk user id for object key")
    try:
        parsed_id = uuid.UUID(str(document_id))
    except (ValueError, AttributeError, TypeError) as exc:
        raise ObjectKeyError("document id must be a UUID") from exc

    safe_name = filename.strip()
    if not safe_name or not _SAFE_FILENAME_PATTERN.match(safe_name):
        # Never embed raw user input into a storage key.
        safe_name = "original.pdf"

    key = str(
        PurePosixPath(
            "users",
            clerk_user_id,
            "documents",
            str(parsed_id),
            safe_name,
        )
    )
    if ".." in key.split("/"):
        raise ObjectKeyError("object key must not contain path traversal")
    return key


class StorageService:
    """Upload / download / delete / exists against the private bucket."""

    def __init__(
        self,
        client: BaseClient | None = None,
        bucket: str | None = None,
    ) -> None:
        self._client = client
        self._bucket = bucket

    @property
    def client(self) -> BaseClient:
        if self._client is None:
            self._client = get_s3_client()
        return self._client

    @property
    def bucket(self) -> str:
        if self._bucket is None:
            self._bucket = get_storage_bucket()
        return self._bucket

    # -- operations -------------------------------------------------------

    def upload_fileobj(
        self,
        key: str,
        fileobj: BinaryIO,
        *,
        content_type: str = "application/pdf",
        length: int | None = None,
    ) -> None:
        """Stream an object into storage without buffering it all in memory."""
        try:
            extra = {"ContentType": content_type}
            if length is not None:
                extra["ContentLength"] = length
            self.client.upload_fileobj(
                fileobj,
                self.bucket,
                key,
                ExtraArgs=extra,
            )
        except (EndpointConnectionError, ClientError) as exc:
            logger.warning("Upload failed for key %s: %s", key, type(exc).__name__)
            raise StorageUnavailableError("storage upload failed") from exc

    def upload_bytes(
        self,
        key: str,
        data: bytes,
        *,
        content_type: str = "application/octet-stream",
    ) -> None:
        """Upload a small in-memory payload (tests, tiny metadata files)."""
        import io

        self.upload_fileobj(key, io.BytesIO(data), content_type=content_type)

    def download_fileobj(self, key: str, fileobj: BinaryIO) -> None:
        """Stream an object out of storage into a file-like object."""
        try:
            self.client.download_fileobj(self.bucket, key, fileobj)
        except ClientError as exc:
            code = _error_code(exc)
            if code in {"404", "NoSuchKey", "NotFound"}:
                raise StorageObjectNotFoundError(key) from exc
            logger.warning(
                "Download failed for key %s: %s", key, type(exc).__name__
            )
            raise StorageUnavailableError("storage download failed") from exc
        except EndpointConnectionError as exc:
            logger.warning(
                "Download connectivity failure for key %s", key
            )
            raise StorageUnavailableError("storage download failed") from exc

    def download_bytes(self, key: str) -> bytes:
        """Read an object fully into memory (small objects only)."""
        import io

        buffer = io.BytesIO()
        self.download_fileobj(key, buffer)
        return buffer.getvalue()

    def delete(self, key: str) -> bool:
        """Delete an object. Returns True if deleted, False if absent."""
        try:
            self.client.delete_object(Bucket=self.bucket, Key=key)
            return True
        except ClientError as exc:
            code = _error_code(exc)
            if code in {"404", "NoSuchKey", "NotFound"}:
                return False
            logger.warning("Delete failed for key %s: %s", key, type(exc).__name__)
            raise StorageUnavailableError("storage delete failed") from exc
        except EndpointConnectionError as exc:
            raise StorageUnavailableError("storage delete failed") from exc

    def exists(self, key: str) -> bool:
        """Return True when the object exists in the private bucket."""
        try:
            self.client.head_object(Bucket=self.bucket, Key=key)
            return True
        except ClientError as exc:
            code = _error_code(exc)
            if code in {"404", "NoSuchKey", "NotFound"}:
                return False
            if code in {"403", "AccessDenied"}:
                # Treat inaccessible-as-missing for private buckets rather
                # than leaking permission details.
                return False
            logger.warning(
                "Exists check failed for key %s: %s", key, type(exc).__name__
            )
            raise StorageUnavailableError("storage exists check failed") from exc
        except EndpointConnectionError as exc:
            raise StorageUnavailableError("storage exists check failed") from exc

    def health_check(self) -> None:
        """Verify credentials + bucket accessibility without touching files.

        Raises:
            StorageNotConfiguredError: environment missing.
            StorageUnavailableError: unreachable, bad credentials, or the
                bucket is missing/inaccessible.
        """
        try:
            self.client.head_bucket(Bucket=self.bucket)
        except StorageNotConfiguredError:
            raise
        except ClientError as exc:
            logger.warning(
                "Storage health check rejected: %s", _error_code(exc) or type(exc).__name__
            )
            raise StorageUnavailableError("storage unavailable") from exc
        except EndpointConnectionError as exc:
            logger.warning("Storage health check connectivity failure")
            raise StorageUnavailableError("storage unavailable") from exc
        except Exception as exc:  # noqa: BLE001 — never leak boto internals
            logger.warning(
                "Storage health check failed: %s", type(exc).__name__
            )
            raise StorageUnavailableError("storage unavailable") from exc


def _error_code(exc: ClientError) -> str:
    """Extract a coarse error code from a ClientError (never the message)."""
    error = getattr(exc, "response", {}).get("Error") or {}
    return str(error.get("Code", ""))


def get_storage_service() -> StorageService:
    """FastAPI-friendly factory for the default storage service."""
    return StorageService()
